"""Where the Help menu leads: pages of the HTML API documentation in docs/api/.

The documentation is a static HTML5 site generated by tools/apidoc.py from the compiler's
language information, the SDK's own comments and the reference guides, in English and Pashto
(docs/api/en/, docs/api/ps/), with a language switch on every page. The Help menu opens it in
a browser view inside the IDE (qt/help_viewer.py): each menu entry is one page of the site, in
the interface's language.

This module is toolkit-neutral: it only knows the pages and where they are on disk.
"""

from __future__ import annotations

from pathlib import Path

from thunder_ide.core.toolchain import repository_root

#: Help command -> page, relative to the language's root of the site. Two doors: the guides
#: (the tutorial-like reading, from the language reference to debugging, in reading order) and
#: the front page of the full API reference (keywords, built-ins, SDK modules, instructions).
#: Every other page is one click away inside the site.
HELP_PAGES = {
    "help_guides": "guides/index.html",
    "help_api": "index.html",
}

#: The languages the site exists in; anything else falls back to English.
SITE_LANGUAGES = ("en", "ps")


def api_root() -> Path:
    """The directory of the generated site (docs/api/)."""
    return repository_root() / "docs" / "api"


def site_language(language: str) -> str:
    """The site's language folder for an interface language."""
    return language if language in SITE_LANGUAGES else "en"


def help_page(topic: str, language: str) -> Path:
    """The file to open for a Help command, in the interface's language.

    An unknown topic opens the site's home page; a page that is missing in the chosen language
    (the site is generated as a whole, so this means a stale checkout) falls back to English,
    and a missing site altogether still returns the path, so the viewer can say what is wrong.
    """
    page = HELP_PAGES.get(topic, HELP_PAGES["help_api"])
    preferred = api_root() / site_language(language) / page
    if preferred.is_file():
        return preferred
    english = api_root() / "en" / page
    return english if english.is_file() else preferred


def home_page(language: str) -> Path:
    """The site's home page in the interface's language."""
    return help_page("help_api", language)


def is_site_page(path) -> bool:
    """True when a path is inside the generated site (the viewer keeps links within it)."""
    try:
        Path(path).resolve().relative_to(api_root().resolve())
        return True
    except ValueError:
        return False
